import { readFileSync, writeFileSync } from 'fs';

const src = readFileSync('/private/tmp/claude-501/-Users-bytedance-Workspace-mbt/e83eeb20-3c7c-49f3-9bc0-1285c570fe5e/scratchpad/svgo-upstream/plugins/_collections.js', 'utf8')
  .replace(/export const /g, 'const ') + '\nmodule.exports = { elems, attrsGroups, attrsGroupsDefaults, elemsGroups, presentationNonInheritableGroupAttrs };';

const mod = { exports: {} };
const fn = new Function('module', 'exports', src);
fn(mod, mod.exports);

const { elems, attrsGroups, attrsGroupsDefaults, elemsGroups, presentationNonInheritableGroupAttrs } = mod.exports;

const allowedAttrs = {};
const elemDefaults = {};
const allowedChildren = {};

for (const [name, config] of Object.entries(elems)) {
  const attrs = new Set();
  const defaults = {};
  if (config.attrs) for (const a of config.attrs) attrs.add(a);
  if (config.defaults) for (const [k, v] of Object.entries(config.defaults)) defaults[k] = v;
  for (const g of config.attrsGroups || []) {
    if (attrsGroups[g]) for (const a of attrsGroups[g]) attrs.add(a);
    if (attrsGroupsDefaults[g]) for (const [k, v] of Object.entries(attrsGroupsDefaults[g])) defaults[k] = v;
  }
  allowedAttrs[name] = [...attrs].sort();
  elemDefaults[name] = defaults;
  
  const children = new Set();
  if (config.content) for (const c of config.content) children.add(c);
  if (config.contentGroups) for (const g of config.contentGroups) {
    if (elemsGroups[g]) for (const c of elemsGroups[g]) children.add(c);
  }
  allowedChildren[name] = [...children].sort();
}

const presentationNonInheritable = presentationNonInheritableGroupAttrs ? [...presentationNonInheritableGroupAttrs] : [];

function moonStr(s) { return '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"'; }
function moonSet(arr) { return 'Set([' + arr.map(moonStr).join(', ') + '])'; }
function moonMap(obj) {
  const entries = Object.entries(obj);
  if (entries.length === 0) return 'Map([])';
  return 'Map([' + entries.map(([k, v]) => '(' + moonStr(k) + ', ' + moonStr(v) + ')').join(', ') + '])';
}

let out = '// Generated by scripts/gen-svg-tables.mjs from svgo plugins/_collections.js.\n';
out += '// Do not edit by hand.\n\n';

out += 'let allowed_attrs : Map[String, Set[String]] = Map([\n';
for (const [name, attrs] of Object.entries(allowedAttrs)) {
  out += '  (' + moonStr(name) + ', ' + moonSet(attrs) + '),\n';
}
out += '])\n\n';

out += 'let elem_defaults : Map[String, Map[String, String]] = Map([\n';
for (const [name, defaults] of Object.entries(elemDefaults)) {
  out += '  (' + moonStr(name) + ', ' + moonMap(defaults) + '),\n';
}
out += '])\n\n';

out += 'let allowed_children : Map[String, Set[String]] = Map([\n';
for (const [name, children] of Object.entries(allowedChildren)) {
  out += '  (' + moonStr(name) + ', ' + moonSet(children) + '),\n';
}
out += '])\n\n';

out += 'let known_elements : Set[String] = Set([\n';
out += Object.keys(elems).sort().map(moonStr).join(', ');
out += '])\n\n';

out += 'let presentation_non_inheritable : Set[String] = ' + moonSet(presentationNonInheritable.sort()) + '\n';

writeFileSync('/tmp/svg_tables.mbt', out);
console.log('Generated /tmp/svg_tables.mbt');
console.log('Elements:', Object.keys(elems).length);
console.log('Sample allowed_attrs[rect]:', allowedAttrs['rect']);
