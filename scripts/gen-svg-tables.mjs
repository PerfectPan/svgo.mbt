#!/usr/bin/env node
// Preserve svgo's groups instead of expanding them into every element.
import { writeFileSync } from "node:fs";
import { resolve, join } from "node:path";
import { pathToFileURL } from "node:url";

if (process.argv.length !== 3) {
  console.error("Usage: node scripts/gen-svg-tables.mjs <svgo-dir>");
  process.exit(1);
}
const collections = await import(pathToFileURL(join(resolve(process.argv[2]), "plugins/_collections.js")));
const {
  elems,
  attrsGroups,
  attrsGroupsDefaults,
  attrsGroupsDeprecated,
  elemsGroups,
  presentationNonInheritableGroupAttrs,
  inheritableAttrs,
  pathElems,
  referencesProps,
} = collections;

// The format has no escaping: reject future upstream delimiter collisions
// rather than silently producing ambiguous data. Colons and spaces are literal.
function atom(value) {
  if (typeof value !== "string" || /[|,=\r\n]/.test(value)) {
    throw new Error(`Unsupported table atom: ${JSON.stringify(value)}`);
  }
  return value;
}
const list = (values = []) => [...values].map(atom).join(",");
const pairs = (values = {}) => Object.entries(values).map(([k, v]) => `${atom(k)}=${atom(v)}`).join(",");
const rows = (values, encode) => Object.entries(values).map(([k, v]) => `${atom(k)}|${encode(v)}`);
const constants = {
  svg_attr_groups_data: rows(attrsGroups, list),
  svg_attr_defaults_data: rows(attrsGroupsDefaults, pairs),
  svg_content_groups_data: rows(elemsGroups, list),
  svg_elements_data: rows(elems, (e) =>
    [
      list(e.attrsGroups),
      list(e.attrs),
      pairs(e.defaults),
      list(e.contentGroups),
      list(e.content),
      list(e.deprecated?.safe),
      list(e.deprecated?.unsafe),
    ].join("|"),
  ),
  svg_non_inheritable_data: [list([...presentationNonInheritableGroupAttrs].sort())],
  svg_inheritable_data: [list([...inheritableAttrs].sort())],
  svg_path_elems_data: [list([...pathElems].sort())],
  svg_references_props_data: [list([...referencesProps].sort())],
  svg_deprecated_groups_data: rows(attrsGroupsDeprecated, (d) =>
    [list(d.safe), list(d.unsafe)].join("|"),
  ),
};
let out = "// Generated by scripts/gen-svg-tables.mjs from svgo plugins/_collections.js.\n// Do not edit by hand. Format and lazy expansion: svg_tables_parse.mbt.\n";
for (const [name, lines] of Object.entries(constants)) {
  out += `\n///|\nlet ${name} : String =\n${lines.map((line) => `  #|${line}`).join("\n")}\n`;
}
const output = new URL("../svgo/plugins/svg_tables.mbt", import.meta.url);
writeFileSync(output, out);
console.log(`Generated svgo/plugins/svg_tables.mbt: ${Object.keys(elems).length} elements, ${Buffer.byteLength(out)} bytes`);
